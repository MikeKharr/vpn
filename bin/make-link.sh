#!/usr/bin/env bash
# Собирает ссылки vless:// для одного устройства на ОДНОМ сервере и печатает
# их В ТЕРМИНАЛ. Запускает ВЛАДЕЛЕЦ на своей машине (ADR 2026-10-03-0353, п. 5).
#
# Серверов два (ADR 2026-10-05-2223), и у каждого свой ключ REALITY и своё имя
# маски, поэтому хост — обязательный аргумент, а не умолчание:
#   th2 — Triplify, 160.236.128.28, маска cdn2.zpq.ai. ОСНОВНОЙ (решение
#         владельца 2026-10-06): его профиль включается рабочим.
#   th1 — ReadyIDC, 45.91.134.23, маска cdn.zpq.ai. РЕЗЕРВ: профили остаются
#         в списке ВЫКЛЮЧЕННЫМИ, на них переключаются руками при отказе th2.
# Умолчания у хоста нет намеренно: ключ и имя у хостов разные, и ссылка,
# собранная не тем ключом, выглядит нормально и не подключается.
#
# Публичный ключ REALITY, который спрашивает скрипт, у хостов РАЗНЫЙ:
#   th2 — ~/.config/vpn/th2-reality.pub на Mac владельца. Пара сделана один
#         раз и не меняется (ADR 2026-10-06-1054), и этим ключом профиль th2
#         владелец УЖЕ импортировал на оба устройства — пол для th2 стоит, а
#         запуск нужен только чтобы собрать ту же ссылку заново;
#   th1 — публичная половина пары первого сервера, из менеджера паролей.
#
# Эти ссылки — ПОЛ, который работает без всяких проверок (ADR 2026-10-05-2223,
# п. 4): автопереключение между серверами даёт отдельный JSON-профиль
# (bin/make-happ-json.sh, PR A-3), и он делается ПОВЕРХ пола, после живой
# пробы. Пол ставится первым и в любом случае.
#
# Серверной страницы подписки нет и не будет: путь с токеном на публичном
# адресе — это секрет в URL, который уходит в журналы входа, историю браузера
# и превью мессенджеров, а отзывается только переустановкой у всех устройств.
#
# Что этот скрипт НЕ делает, намеренно:
#   - не пишет ссылку, QR и значения ни в один файл (готовая ссылка — тот же
#     секрет, что UUID; .gitignore — вторая линия, не первая);
#   - не ходит на сервер и ничего оттуда не читает;
#   - не кладёт ссылку в аргументы ни одного процесса: в qrencode она уходит
#     по stdin, иначе её было бы видно в `ps`;
#   - не трогает приватный ключ REALITY: в ссылке стоит ПУБЛИЧНЫЙ (pbk).
#
# На каждое устройство выходит две ссылки, и обе на порт 443 — разница в
# АДРЕСЕ:
#   рабочая  — ИМЕНЕМ маски: адрес берётся из DNS. Переимпортировать её при
#              смене адреса не придётся — она от адреса не зависит;
#   запасная — АДРЕСОМ-литералом с тем же `sni=`, то есть МИНУЯ DNS. Для th2
#              это путь на случай отказа DNS или регистратора (ADR
#              2026-10-05-2223, п. 5); для th1 — ещё и прежний адрес машины,
#              то есть вход через единицу `sni` проекта zpq-ai, куда ведёт
#              откат A-записи без PR (ADR 2026-10-05-1546, п. 5).
#              Импортировать её ВЫКЛЮЧЕННОЙ.
#
# Запуск:  bash bin/make-link.sh <устройство> <хост>
#   например: bash bin/make-link.sh mac th2
set -euo pipefail

# chrome, а не firefox: при ядре Xray >= 26.9.8 гибридный key share
# X25519MLKEM768 в utls есть только у chrome (ADR 2026-10-03-0353, п. 3). Цена
# названа там же — именно chrome режут на части мобильных сетей.
FINGERPRINT="${FINGERPRINT:-chrome}"
# Порт у всех ссылок один — 443: и прямой вход в Xray на обоих серверах, и
# единица `sni` на прежнем адресе th1 слушают его.
PORT_MAIN="${PORT_MAIN:-443}"

label="${1:-}"
if [ -z "$label" ]; then
  printf 'Имя устройства (попадёт в подпись профиля, например mac или iphone)\n> '
  read -r label || true
fi
case "$label" in
  '' ) echo "Имя устройства не задано — ничего не собрано." >&2; exit 1 ;;
  *[!A-Za-z0-9._-]* ) echo "В имени устройства только A-Za-z0-9._- — оно уходит во фрагмент URL." >&2; exit 1 ;;
esac

host="${2:-}"
if [ -z "$host" ]; then
  printf 'Хост: th2 (основной, Triplify) или th1 (резерв, ReadyIDC)\n> '
  read -r host || true
fi
# Карта хостов. Имя маски обязано совпадать с MASK_NAME наложения
# deploy/hosts/<хост>/compose.yml, то есть с `serverNames` REALITY: имени,
# которого там нет, сервер не примет, и рукопожатие не состоится.
# Адреса — не секрет: они публичны через A-записи и записаны в ADR.
case "$host" in
  th2)
    SERVER_NAME='cdn2.zpq.ai'
    FALLBACK_ADDR='160.236.128.28'
    fallback_why='тот же адрес литералом, мимо DNS'
    role='ОСНОВНОЙ'
    ;;
  th1)
    SERVER_NAME='cdn.zpq.ai'
    FALLBACK_ADDR='45.91.134.19'
    fallback_why='ПРЕЖНИЙ адрес машины — вход через единицу sni, мимо DNS'
    role='РЕЗЕРВ'
    ;;
  *)
    echo "Неизвестный хост «${host}»: ожидается th2 (основной) или th1 (резерв). Умолчания нет — у хостов разные ключи REALITY." >&2
    exit 1
    ;;
esac

ask() {
  local name="$1" prompt="$2" form="$3" hint="$4" value=''
  while true; do
    printf '%s (ввод не отображается)\n> ' "$prompt"
    read -rs value || true
    printf '\n'
    if [ -z "$value" ]; then
      echo "Пусто — ничего не собрано." >&2
      exit 1
    fi
    if printf '%s' "$value" | grep -Eq "$form"; then
      break
    fi
    echo "Не та форма: ожидается $hint. Повторите." >&2
  done
  eval "$name=\$value"
}

ask PUBLIC_KEY "Password/PublicKey из вывода xray x25519 — ПУБЛИЧНЫЙ ключ СЕРВЕРА $host" \
               '^[A-Za-z0-9_-]{43}$' '43 знака base64url'
ask UUID       "UUID устройства $label"  \
               '^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[1-5][0-9a-fA-F]{3}-[89abAB][0-9a-fA-F]{3}-[0-9a-fA-F]{12}$' 'UUID из uuidgen'
ask SHORT_ID   "shortId устройства $label" \
               '^[0-9a-f]{8}$' '8 знаков hex'

# Адрес и `sni=` — РАЗНЫЕ параметры: у рабочей ссылки они совпадают (имя
# маски), у запасной адрес — литерал, а `sni` остаётся именем маски. Иначе
# REALITY не нашёл бы его в `serverNames`, и рукопожатие не состоялось бы ни
# по одному пути.
#
# Подпись профиля несёт ИМЯ ХОСТА: в Happ профилей теперь четыре на
# устройство (два хоста × две ссылки), и без хоста в подписи владелец не
# отличил бы основной от резерва в списке.
link() {
  local addr="$1" port="$2" suffix="$3"
  printf 'vless://%s@%s:%s?encryption=none&security=reality&type=tcp&flow=xtls-rprx-vision&sni=%s&fp=%s&pbk=%s&sid=%s#%s\n' \
    "$UUID" "$addr" "$port" "$SERVER_NAME" "$FINGERPRINT" "$PUBLIC_KEY" "$SHORT_ID" "${label}-${host}${suffix}"
}

main_link=$(link "$SERVER_NAME" "$PORT_MAIN" '')
fallback_link=$(link "$FALLBACK_ADDR" "$PORT_MAIN" '-ip')

show() {
  local title="$1" value="$2"
  printf '\n=== %s ===\n%s\n' "$title" "$value"
  if command -v qrencode >/dev/null 2>&1; then
    # -t ANSIUTF8 — QR рисуется знаками в терминале. Файла не возникает:
    # вывод идёт в stdout, -o не передаётся.
    # Ссылка уходит по stdin, а не аргументом: аргументы процесса видны в `ps`
    # процессам того же пользователя и root, а готовая ссылка — секрет того же
    # веса, что UUID. Это то же соображение, по которому
    # deploy/render/render.sh отказывается от `sed "s|…|$val|"`
    # (находки reviewer и compliance).
    printf '%s' "$value" | qrencode -t ANSIUTF8 -m 1
  else
    echo '(QR не нарисован: нет qrencode. Поставить — brew install qrencode;'
    echo ' без него ссылку переносить AirDrop'"'"'ом или через менеджер паролей.)'
  fi
}

show "$label/$host ($role) — рабочая: имя $SERVER_NAME, порт $PORT_MAIN" "$main_link"
show "$label/$host ($role) — запасная: $fallback_why ($FALLBACK_ADDR), порт $PORT_MAIN (импортировать выключенной)" "$fallback_link"

if [ "$host" = th2 ]; then
  enable_hint='  2. Профиль th2 — РАБОЧИЙ: включить его в Happ как действующий. Профили th1
     остаются в списке ВЫКЛЮЧЕННЫМИ — на них переключаются руками, если th2
     недоступен (ADR 2026-10-05-2223, п. 4, «пол»).'
else
  enable_hint='  2. Профиль th1 — РЕЗЕРВНЫЙ: импортировать ВЫКЛЮЧЕННЫМ. Рабочим стоит th2
     (решение владельца 2026-10-06); th1 включается руками при его отказе.'
fi

cat <<EOF

Дальше:
  1. Рабочую ссылку (имя ${SERVER_NAME}, адрес из DNS) импортировать в Happ
     (id6504287215). Переимпортировать её при смене адреса сервера не нужно:
     она задана именем. Запасную (${FALLBACK_ADDR} литералом, минуя DNS) — в
     список, ВЫКЛЮЧЕННОЙ: она нужна, когда DNS или имя недоступны.
${enable_hint}
  3. Правила маршрутизации: direct на zpq.ai, challenge.zpq.ai, mail.zpq.ai,
     ${SERVER_NAME} и локальные сети — иначе трафик к своему же серверу идёт
     петлёй через него.
  4. Публичный ключ у серверов РАЗНЫЙ (ADR 2026-10-05-2223, п. 3): ссылки
     второго хоста собираются отдельным запуском
     «bash bin/make-link.sh ${label} <другой хост>», а не копией этих.
  5. Вывод выше — секрет того же веса, что UUID. Очистить историю терминала:
       clear && printf '\\033[3J'
EOF
