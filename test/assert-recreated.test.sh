#!/usr/bin/env bash
# Приманки для deploy/assert-recreated.sh — держателя требования «Xray
# пересоздан этой выкаткой». Исполняется сам скрипт, тот же файл, который
# уезжает на сервер rsync'ом и вызывается шагом выкатки.
#
# Главный случай здесь — «тот же Id»: он воспроизводит дефект, из-за которого
# ротация ключа и отзыв устройства не вступали в силу при зелёной выкатке
# (блокирующая reviewer к первому кругу PR #2).
set -euo pipefail

here=$(cd "$(dirname "$0")" && pwd)
script="$here/../deploy/assert-recreated.sh"
[ -x "$script" ] || { echo "нет $script"; exit 2; }

pass=0
fail=0

# $1 — что проверяем, $2 — ожидаемый код, $3 — ожидаемый кусок текста,
# далее — четыре аргумента скрипта.
case_is() {
  local title="$1" want="$2" needle="$3"; shift 3
  local rc=0 out
  out=$(bash "$script" "$@" 2>&1) || rc=$?
  if [ "$rc" = "$want" ] && printf '%s' "$out" | grep -qF -- "$needle"; then
    pass=$((pass + 1)); printf 'ok   %s (код %s)\n' "$title" "$rc"
  else
    fail=$((fail + 1)); printf 'ПРОВАЛ %s: ждали код %s и текст «%s», получили код %s\n%s\n' \
      "$title" "$want" "$needle" "$rc" "$out"
  fi
}

OLD='2026-10-03T16:07:30.100000000Z'
NEW='2026-10-03T16:07:33.375590123Z'

case_is 'пересоздан: Id сменился, xray позже render' 0 'xray стартовал не раньше render' \
  aaa111 bbb222 "$OLD" "$NEW"
case_is 'первая выкатка: контейнера до не было' 0 'первая выкатка' \
  '' bbb222 "$OLD" "$NEW"

case_is 'НЕ пересоздан: тот же Id' 1 'НЕ пересоздан' \
  aaa111 aaa111 "$OLD" "$NEW"
case_is 'контейнера после выкатки нет' 1 'не поднялся' \
  aaa111 '' "$OLD" "$NEW"
case_is 'xray стартовал раньше render' 1 'РАНЬШЕ render' \
  aaa111 bbb222 "$NEW" "$OLD"

# Дробная часть разной ширины — именно та форма, в которой сравнение строк
# «как есть» дало бы ЛОЖНОЕ «xray раньше»: 33.3 лексикографически больше 33.25.
case_is 'дробные части разной ширины: 33.25 < 33.3' 0 'не раньше render' \
  aaa111 bbb222 '2026-10-03T16:07:33.25Z' '2026-10-03T16:07:33.3Z'
case_is 'дробные части разной ширины, обратный порядок' 1 'РАНЬШЕ render' \
  aaa111 bbb222 '2026-10-03T16:07:33.3Z' '2026-10-03T16:07:33.25Z'
case_is 'равные времена — не отказ' 0 'не раньше render' \
  aaa111 bbb222 "$NEW" "$NEW"

case_is 'время не разобралось' 2 'не разобралось' \
  aaa111 bbb222 'никогда' "$NEW"
case_is 'не то число аргументов' 2 'ожидается 4 аргумента' \
  aaa111 bbb222 "$NEW"

printf '\nитог: пройдено %s, провалено %s\n' "$pass" "$fail"
[ "$fail" -eq 0 ]
