#!/usr/bin/env bash
# Приманки deploy/bootstrap.sh. Прогоняются на своей машине и в CI, без
# сервера и без root.
#
# Что здесь ВООБЩЕ можно проверить без машины, а что нельзя, названо прямо:
#   можно — разбор аргументов (имя пользователя выкатки, второй аргумент) и
#           то, что запуск СО STDIN не теряет тело скрипта;
#   нельзя — ufw, fail2ban, sshd, Docker и отчёт: они требуют root и Ubuntu.
#           Их различает только живой прогон на сервере, и его вывод —
#           доказательство в описании PR, а не этот файл.
#
# Главная приманка — «stdin не съедается». Разрешение владельца 2026-10-06
# запускать скрипт формой `ssh triplify 'bash -s -- ops' < deploy/bootstrap.sh`
# опирается ровно на одно свойство файла: тело завёрнуто в группу `{ … }`, и
# bash дочитывает её до закрывающей скобки ПРЕЖДЕ, чем исполнить хоть одну
# команду внутри. Без группы первая же команда, читающая stdin (а это apt на
# conffile-вопросе — урок адвента 2026-09-07), съедает ОСТАТОК СКРИПТА:
# прогон при этом выглядит успешным, потому что не исполненные строки не
# жалуются. Приманка ловит именно это и именно через конвейер — через файл
# stdin перемещаемый, и bash возвращает позицию сам, то есть отказ не
# воспроизводится.
set -euo pipefail

here=$(cd "$(dirname "$0")" && pwd)
script="$here/../deploy/bootstrap.sh"
[ -r "$script" ] || { echo "нет $script"; exit 2; }

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

pass=0
fail=0

ok()   { pass=$((pass + 1)); printf 'ok   %s\n' "$1"; }
bad()  { fail=$((fail + 1)); printf 'ПРОВАЛ %s: %s\n' "$1" "$2"; }

# $1 — заголовок, $2 — ожидаемый код, $3 — кусок, который обязан быть в
# выводе, далее — аргументы скрипта. Запуск ФАЙЛОМ: проверяется разбор
# аргументов, а не чтение ввода.
case_is() {
  local title="$1" want_rc="$2" needle="$3"; shift 3
  local out rc=0
  out=$(bash "$script" "$@" 2>&1) || rc=$?
  if [ "$rc" != "$want_rc" ]; then
    bad "$title" "ждали код $want_rc, получили $rc"
    return
  fi
  if ! printf '%s' "$out" | grep -qF -- "$needle"; then
    # Скобки у имени обязательны: закрывающая «»» — многобайтная, и без них
    # bash считает её частью имени переменной и падает на `set -u`
    # сообщением «needle»: unbound variable». Поймано мутационной проверкой
    # формы FAIL2BAN_IGNOREIP: до неё эта ветвь ни разу не исполнялась.
    bad "$title" "в выводе нет куска «${needle}»"
    return
  fi
  ok "$title"
}

# То же, но с переменной окружения перед аргументами: `$1` — заголовок,
# `$2` — ожидаемый код, `$3` — кусок вывода, `$4` — значение
# FAIL2BAN_IGNOREIP, далее аргументы скрипта.
case_ignoreip() {
  local title="$1" want_rc="$2" needle="$3" value="$4"; shift 4
  local out rc=0
  out=$(FAIL2BAN_IGNOREIP="$value" bash "$script" "$@" 2>&1) || rc=$?
  if [ "$rc" != "$want_rc" ]; then
    bad "$title" "ждали код $want_rc, получили $rc"
    return
  fi
  if ! printf '%s' "$out" | grep -qF -- "$needle"; then
    # Скобки у имени — по той же причине, что в case_is выше.
    bad "$title" "в выводе нет куска «${needle}»"
    return
  fi
  ok "$title"
}

# Вырезает ТЕЛО функции верхнего уровня из файла скрипта: от строки
# «<имя>() {» до первой закрывающей скобки в нулевой колонке. Так приманки
# ниже проверяют настоящий код bootstrap.sh, а не его пересказ в тесте, — и
# мутация в самом bootstrap.sh до них доезжает.
# $1 — файл, $2 — имя функции.
extract_fn() {
  awk -v want="$2() {" '
    $0 == want { inside = 1 }
    inside     { print }
    inside && $0 == "}" { exit }
  ' "$1"
}

echo '--- аргументы: имя пользователя выкатки ---'
# Имя не задано — отказ, а не умолчание. Умолчание в файле означало бы, что
# на третьей машине пользователь выкатки получит имя, которое никто не
# выбирал, и оно же будет известно каждому, кто читает репозиторий.
case_is 'имя не задано — отказ'            1 'не задано имя пользователя' ''
# Имена из списка угадываемых. `ops` в этом списке НЕТ намеренно: его выбрал
# владелец 2026-10-06, и именно он уезжает в секрет SSH_USER.
case_is 'имя root отвергнуто'              1 'угадывается с первой попытки' root
case_is 'имя ubuntu отвергнуто'            1 'угадывается с первой попытки' ubuntu
case_is 'имя advent отвергнуто'            1 'угадывается с первой попытки' advent
case_is 'имя deploy отвергнуто'            1 'угадывается с первой попытки' deploy
# Форма имени: заглавные, точка, начало с цифры, два знака — всё это Linux
# либо не примет, либо примет с сюрпризами в правах на /home.
case_is 'имя с заглавными — отказ по форме' 1 'не той формы' Ops
case_is 'имя с точкой — отказ по форме'     1 'не той формы' 'ops.th2'
case_is 'имя с цифры — отказ по форме'      1 'не той формы' '2ops'
case_is 'имя в два знака — отказ по форме'  1 'не той формы' op

echo '--- аргументы: второй аргумент ---'
# Второй аргумент — только --disable-root-login. Опечатка в нём не должна
# тихо сойти за первую фазу: тогда владелец думал бы, что вход для root
# закрыт, а он был бы открыт.
case_is 'опечатка во втором аргументе — отказ' 1 'может быть только --disable-root-login' ops --disable-root
case_is 'лишний аргумент — отказ'              1 'может быть только --disable-root-login' ops --force

echo '--- годное имя доходит до проверки на root ---'
# Положительный контроль: без него все приманки выше зеленели бы и на
# скрипте, который отвергает ЛЮБОЙ аргумент. Прогон идёт не от root, поэтому
# годное имя обязано дойти именно до этой проверки — и дальше не пойти.
case_is 'ops принят, отказ уже на «не root»'   1 'запускать от root' ops
case_is 'ops --disable-root-login принят'      1 'запускать от root' ops --disable-root-login

echo '--- FAIL2BAN_IGNOREIP: форма проверяется до root ---'
# Негодный адрес обязан остановить скрипт ЗДЕСЬ, а не доехать до
# /etc/fail2ban/jail.local: fail2ban отвергает jail с негодным ignoreip
# целиком, то есть прогон был бы зелёным, а машина — без бана вовсе.
case_ignoreip 'не адрес — отказ'                1 'не адрес IPv4' 'zzz' ops
case_ignoreip 'обрезанный адрес — отказ'        1 'не адрес IPv4' '1.2.3' ops
# Отказы, которые прежний образец (считавший только число знаков) ПРОПУСКАЛ.
# Каждый из них fail2ban отвергает, унося с собой весь jail sshd.
case_ignoreip 'октет 999 — отказ'               1 'не адрес IPv4' '999.1.1.1' ops
case_ignoreip 'октет 256 — отказ'               1 'не адрес IPv4' '256.0.0.1' ops
case_ignoreip 'пять октетов — отказ'            1 'не адрес IPv4' '1.2.3.4.5' ops
case_ignoreip 'ведущий нуль в октете — отказ'   1 'не адрес IPv4' '01.2.3.4' ops
case_ignoreip 'префикс 33 — отказ'              1 'не адрес IPv4' '45.91.134.19/33' ops
case_ignoreip 'префикс 99 — отказ'              1 'не адрес IPv4' '45.91.134.19/99' ops
case_ignoreip 'пустой префикс — отказ'          1 'не адрес IPv4' '1.2.3.4/' ops
# Проверяется КАЖДОЕ слово списка: иначе один годный адрес впереди пропускал
# бы любую строку за ним.
case_ignoreip 'негодный второй в списке — отказ' 1 'не адрес IPv4' '45.91.134.19 1.2.3' ops
# Положительные контроли: годное значение не отвергается и доезжает до
# проверки на root. Края диапазона здесь обязательны — строгий образец легко
# сделать строже нужного, и тогда законный адрес не прошёл бы.
case_ignoreip 'адрес принят'                    1 'запускать от root' '45.91.134.19' ops
case_ignoreip 'нижний край 0.0.0.0 принят'      1 'запускать от root' '0.0.0.0' ops
case_ignoreip 'верхний край 255.255.255.255'    1 'запускать от root' '255.255.255.255' ops
case_ignoreip 'адрес с маской принят'           1 'запускать от root' '45.91.134.19/32' ops
case_ignoreip 'префикс 32 принят'               1 'запускать от root' '1.2.3.4/32' ops
case_ignoreip 'сеть 10.0.0.0/8 принята'         1 'запускать от root' '10.0.0.0/8' ops
case_ignoreip 'список годных принят'            1 'запускать от root' '45.91.134.19 10.0.0.0/8' ops
# Переменной нет вовсе — скрипт обязан работать как прежде (значение
# необязательно: на третьей машине ignoreip может быть не нужен).
case_ignoreip 'пустое значение — не отказ'      1 'запускать от root' '' ops

# Красная ветвь. Мутация адресуется НОМЕРОМ СТРОКИ: строка с `grep -Eq`
# заменяется на прежний нестрогий образец. Если приманки выше его не
# различают, они не проверяют ничего.
n=$(grep -n 'F2B_OCTET}(\\\.' "$script" | head -1 | cut -d: -f1)
if [ -z "$n" ]; then
  bad 'мутация образца собирается' 'строка с проверкой формы не найдена — мутацию некуда вставить'
else
  awk -v n="$n" \
    'NR==n { print "    printf '"'"'%s'"'"' \"$a\" | grep -Eq '"'"'^([0-9]{1,3}\\.){3}[0-9]{1,3}(/[0-9]{1,2})?$'"'"' \\"; next } { print }' \
    "$script" > "$work/loose-ip.sh"
  printf '   мутация в строку %s: %s\n' "$n" "$(sed -n "${n}p" "$work/loose-ip.sh")"
  if [ "$(sed -n "${n}p" "$work/loose-ip.sh")" = "$(sed -n "${n}p" "$script")" ]; then
    bad 'мутация образца собирается' 'строка не изменилась — мутация ничего не мутировала'
  else
    # С прежним образцом 999.1.1.1 проходит форму и скрипт доезжает до
    # проверки на root — тот же код 1, но ПО ДРУГОЙ причине, поэтому
    # различаем по тексту, а не по коду.
    mut_out=$(FAIL2BAN_IGNOREIP='999.1.1.1' bash "$work/loose-ip.sh" ops 2>&1 || true)
    if printf '%s' "$mut_out" | grep -qF 'запускать от root'; then
      ok 'мутация краснеет: с прежним образцом 999.1.1.1 проходит проверку формы'
    else
      bad 'мутация краснеет' "с прежним образцом 999.1.1.1 всё равно отвергнут — значит приманки выше не различают образцы. Вывод: ${mut_out}"
    fi
  fi
fi

echo '--- в jail.local уезжают проверенные слова, а не исходная строка ---'
# Прежняя форма писала `IGNOREIP="${IGNOREIP} ${FAIL2BAN_IGNOREIP}"` — исходную
# строку целиком. Перевод строки внутри значения проверку формы проходил (цикл
# разбивает значение по IFS), а в файле давал ВТОРУЮ строку, которую fail2ban
# разбирает как отдельный параметр и отвергает jail целиком.
#
# Проверяется НАСТОЯЩИЙ код bootstrap.sh, вырезанный по позиции: блок
# накопления (от `IGNOREIP="127.0.0.1/8 ::1"` до ближайшего `fi`) и блок
# записи jail.local (от `{` до `} > /etc/fail2ban/jail.local`), у которого
# перенаправление уводится в файл обвязки.
run_jail() {  # $1 — файл скрипта, $2 — значение FAIL2BAN_IGNOREIP; печатает jail.local
  local src="$1" value="$2" h="$work/jail-harness.sh" out="$work/jail.local"
  local a b c d
  a=$(grep -n '^IGNOREIP="127\.0\.0\.1/8 ::1"$' "$src" | head -1 | cut -d: -f1)
  b=$(awk -v s="$a" 'NR>s && $0 == "fi" { print NR; exit }' "$src")
  d=$(grep -n '^} > /etc/fail2ban/jail\.local$' "$src" | head -1 | cut -d: -f1)
  c=$(awk -v e="$d" '$0 == "{" && NR < e { n = NR } END { print n }' "$src")
  [ -n "$a" ] && [ -n "$b" ] && [ -n "$c" ] && [ -n "$d" ] || { echo "НЕТ-ФИКСТУРЫ a=$a b=$b c=$c d=$d"; return; }
  {
    echo 'set -uo pipefail'
    echo 'die() { echo "die $*" >&2; exit 1; }'
    sed -n "${a},${b}p" "$src"
    # SC2016: `$JAIL_OUT` обязан попасть в файл обвязки НЕРАСКРЫТЫМ и
    # раскрыться при её прогоне — это и есть перенаправление в фикстуру.
    # shellcheck disable=SC2016
    sed -n "${c},${d}p" "$src" | sed 's|> /etc/fail2ban/jail\.local$|> "$JAIL_OUT"|'
  } > "$h"
  : > "$out"
  FAIL2BAN_IGNOREIP="$value" JAIL_OUT="$out" bash "$h" >/dev/null 2>&1 || true
  cat "$out"
}

# Фикстура обязана собираться и работать на годном значении — иначе проверка
# ниже зеленела бы на пустом файле.
base=$(run_jail "$script" '45.91.134.19')
if ! printf '%s\n' "$base" | grep -q '^ignoreip = 127\.0\.0\.1/8 ::1 45\.91\.134\.19$'; then
  bad 'фикстура jail.local собирается' "в собранном jail.local нет ожидаемой строки ignoreip. Получили: $(printf '%s' "$base" | tr '\n' '; ')"
else
  ok 'фикстура jail.local собирается: проверенные слова доезжают до файла'

  nl_value=$'45.91.134.19\n10.0.0.0/8'
  got=$(run_jail "$script" "$nl_value")
  lines=$(printf '%s\n' "$got" | grep -c '^ignoreip')
  if [ "$lines" = 1 ] && printf '%s\n' "$got" | grep -q '^ignoreip = 127\.0\.0\.1/8 ::1 45\.91\.134\.19 10\.0\.0\.0/8$'; then
    ok 'перевод строки внутри значения не даёт лишней строки в jail.local'
  else
    bad 'перевод строки не даёт лишней строки' "строк ignoreip: ${lines}; файл: $(printf '%s' "$got" | tr '\n' '; ')"
  fi

  # Красная ветвь: возвращается прежняя форма — накопление заменяется записью
  # исходной строки после цикла. Адресуется номером строки накопления.
  # SC2016 здесь и ниже: ищется и печатается ТЕКСТ строки скрипта, раскрывать
  # его нельзя.
  # shellcheck disable=SC2016
  n=$(grep -n '^    IGNOREIP="\${IGNOREIP} \${a}"$' "$script" | head -1 | cut -d: -f1)
  if [ -z "$n" ]; then
    bad 'мутация jail.local собирается' 'строка накопления внутри цикла не найдена — мутацию некуда вставить'
  else
    awk -v n="$n" \
      'NR==n { next } $0 == "  done" && NR > n && !done_seen { print; print "  IGNOREIP=\"${IGNOREIP} ${FAIL2BAN_IGNOREIP}\""; done_seen=1; next } { print }' \
      "$script" > "$work/raw-ignoreip.sh"
    if [ "$(wc -l < "$work/raw-ignoreip.sh")" != "$(wc -l < "$script")" ]; then
      bad 'мутация jail.local собирается' 'мутированный файл не того размера — замена не состоялась'
    fi
    # shellcheck disable=SC2016
    printf '   мутация: строка %s убрана, после цикла возвращено IGNOREIP="${IGNOREIP} ${FAIL2BAN_IGNOREIP}"\n' "$n"
    mut=$(run_jail "$work/raw-ignoreip.sh" "$nl_value")
    mut_lines=$(printf '%s\n' "$mut" | grep -c '^ignoreip')
    if [ "$mut_lines" -gt 1 ] || printf '%s\n' "$mut" | grep -q '^10\.0\.0\.0/8$'; then
      ok 'мутация краснеет: с прежней формой в jail.local появляется вторая строка'
    else
      bad 'мутация краснеет' "с возвращённой прежней формой лишней строки нет — значит приманка не различает формы. Файл: $(printf '%s' "$mut" | tr '\n' '; ')"
    fi
  fi
fi

echo '--- reload_sshd не перезапускает ssh.socket ---'
# Чем это куплено. Первый живой прогон на th2 обрывался ровно здесь: функция
# делала `systemctl restart ssh` и сразу `systemctl restart ssh.socket`, и
# вторая команда убивала сессию, через которую скрипт шёл на stdin (у
# ssh.service `Requires=ssh.socket`). Файрвол, fail2ban, автообновления и
# отчёт не исполнялись.
#
# Проверяется НАСТОЯЩЕЕ тело функции из bootstrap.sh, вырезанное по позиции,
# с подставными `systemctl`, `sshd` и `die`, которые только пишут свой argv в
# журнал. Так видно, какие команды функция ВЫПОЛНЯЕТ, а не что о ней
# написано.
run_reload() {  # $1 — файл скрипта; печатает журнал вызовов
  local src="$1" h="$work/reload-harness.sh"
  {
    # Подставные команды пишутся в файл обвязки как ТЕКСТ: расширяться `$*` и
    # `$CALLS` обязаны при прогоне обвязки, а не здесь.
    cat <<'PRELUDE'
set -uo pipefail
sshd()      { echo "sshd $*" >> "$CALLS"; return 0; }
systemctl() { echo "systemctl $*" >> "$CALLS"; return 0; }
die()       { echo "die $*" >> "$CALLS"; exit 1; }
PRELUDE
    extract_fn "$src" reload_sshd
    echo 'reload_sshd'
  } > "$h"
  : > "$work/calls"
  CALLS="$work/calls" bash "$h" >/dev/null 2>&1 || true
  cat "$work/calls"
}

if ! extract_fn "$script" reload_sshd | grep -q 'systemctl restart ssh$'; then
  bad 'фикстура reload_sshd собирается' 'в вырезанном теле reload_sshd нет «systemctl restart ssh» — приманка ниже проверяла бы не то'
else
  calls=$(run_reload "$script")
  if printf '%s\n' "$calls" | grep -q '^systemctl restart ssh$'; then
    ok 'reload_sshd перезапускает службу ssh'
  else
    bad 'reload_sshd перезапускает службу ssh' "журнал вызовов: $(printf '%s' "$calls" | tr '\n' '; ')"
  fi
  if printf '%s\n' "$calls" | grep -q 'ssh\.socket'; then
    bad 'ssh.socket не трогается' "функция обращается к ssh.socket — запуск формой «ssh … bash -s < bootstrap.sh» снова оборвётся. Журнал: $(printf '%s' "$calls" | tr '\n' '; ')"
  else
    ok 'ssh.socket не трогается: сессия запуска не умирает'
  fi

  # Красная ветвь. Мутация адресуется НОМЕРОМ СТРОКИ: за строкой перезапуска
  # службы дописывается прежний перезапуск сокета.
  n=$(grep -n '^  systemctl restart ssh$' "$script" | head -1 | cut -d: -f1)
  if [ -z "$n" ]; then
    bad 'мутация reload_sshd собирается' 'строка «  systemctl restart ssh» не найдена — мутацию некуда вставить'
  else
    awk -v n="$n" 'NR==n { print; print "  systemctl restart ssh.socket"; next } { print }' \
      "$script" > "$work/socket-back.sh"
    printf '   мутация в строку %s: %s\n' "$((n + 1))" "$(sed -n "$((n + 1))p" "$work/socket-back.sh")"
    if printf '%s\n' "$(run_reload "$work/socket-back.sh")" | grep -q 'ssh\.socket'; then
      ok 'мутация краснеет: возвращённый перезапуск сокета виден приманке'
    else
      bad 'мутация краснеет' 'с возвращённым «systemctl restart ssh.socket» приманка его не заметила — значит она не различает прежнюю форму от исправленной'
    fi
  fi
fi

echo '--- фильтр посторонних слушателей ---'
# Первый живой прогон на th2 выдал «на внешних адресах слушают ещё порты: 53».
# Это systemd-resolved на 127.0.0.53 и 127.0.0.54 — петлевые адреса, снаружи
# недостижимые. Прежний образец исключал только 127.0.0.1.
#
# Фикстура — вывод `ss -Hltn` в его настоящих четырёх колонках
# (State Recv-Q Send-Q Local Peer): функция берёт четвёртое поле.
cat > "$work/ss-out" <<'EOF'
LISTEN 0 4096 127.0.0.53:53 0.0.0.0:*
LISTEN 0 4096 127.0.0.54:53 0.0.0.0:*
LISTEN 0 4096 127.0.0.1:631 0.0.0.0:*
LISTEN 0 128 0.0.0.0:22 0.0.0.0:*
LISTEN 0 511 [::]:443 [::]:*
LISTEN 0 4096 [::1]:5432 [::]:*
LISTEN 0 4096 0.0.0.0:3389 0.0.0.0:*
EOF

run_filter() {  # $1 — файл скрипта; печатает выход фильтра на фикстуре
  local src="$1" h="$work/filter-harness.sh"
  {
    echo 'set -uo pipefail'
    extract_fn "$src" extra_listeners
    echo 'extra_listeners'
  } > "$h"
  bash "$h" < "$work/ss-out"
}

if ! extract_fn "$script" extra_listeners | grep -q 'grep -vE'; then
  bad 'фикстура фильтра собирается' 'в вырезанном теле extra_listeners нет исключающего grep — приманка проверяла бы не то'
else
  got=$(run_filter "$script" | tr '\n' ' ')
  if [ "$got" = "3389 " ]; then
    ok 'фильтр оставляет только настоящий посторонний порт (3389)'
  else
    bad 'фильтр оставляет только 3389' "получили «${got}»: петлевые 53/631/5432 или штатные 22/443 просочились"
  fi

  # Красная ветвь: образец заменяется на прежний, исключавший только
  # 127.0.0.1. Адресуется номером строки.
  n=$(grep -n "grep -vE '\^(127" "$script" | head -1 | cut -d: -f1)
  if [ -z "$n" ]; then
    bad 'мутация фильтра собирается' 'строка с исключающим образцом не найдена — мутацию некуда вставить'
  else
    awk -v n="$n" \
      'NR==n { print "    | grep -vE '"'"'^(127\\.0\\.0\\.1|\\[::1\\]|\\[::ffff:127\\.0\\.0\\.1\\])'"'"' \\"; next } { print }' \
      "$script" > "$work/old-filter.sh"
    printf '   мутация в строку %s: %s\n' "$n" "$(sed -n "${n}p" "$work/old-filter.sh")"
    if run_filter "$work/old-filter.sh" | grep -qx 53; then
      ok 'мутация краснеет: с прежним образцом 53 от systemd-resolved снова считается внешним'
    else
      bad 'мутация краснеет' 'с прежним образцом порт 53 всё равно отфильтрован — значит приманка не различает образцы'
    fi
  fi
fi

echo '--- stdin не съедается при запуске конвейером ---'
# Фикстура собирается ИЗ САМОГО bootstrap.sh и адресуется ПОЗИЦИЕЙ: строкой,
# открывающей группу. Сразу после неё вставляются две строки — команда,
# читающая stdin, и метка. Если тело скрипта не защищено группой, `read`
# съедает строку с меткой, и метка не печатается.
open_line=$(grep -n '^{$' "$script" | head -1 | cut -d: -f1)
if [ -z "$open_line" ]; then
  bad 'фикстура собирается' 'в bootstrap.sh нет строки «{», открывающей группу тела — приманка ниже проверяла бы не то'
else
  awk -v n="$open_line" \
    'NR==n { print; print "read -r stolen || true"; print "echo MARKER_REACHED"; next } { print }' \
    "$script" > "$work/with-group.sh"
  # Мутация: группа снята. Обе скобки заменяются на no-op, то есть тело
  # остаётся тем же набором команд, и меняется ровно одно — разбирает ли bash
  # его целиком до первого исполнения.
  sed -e 's|^{$|: группа снята|' -e 's|^} </dev/null$|: группа снята|' \
    "$work/with-group.sh" > "$work/no-group.sh"
  if ! grep -qF ': группа снята' "$work/no-group.sh"; then
    bad 'мутация собирается' 'замена скобок группы не нашла ни одной строки — мутация ничего не изменила'
  fi

  # SC2002: «лишний cat» здесь — ПРЕДМЕТ проверки, а не небрежность. Через
  # `bash -s < файл` stdin перемещаемый, bash сам возвращает позицию, и отказ
  # не воспроизводится вовсе; нужен именно КОНВЕЙЕР, как у ssh.
  # shellcheck disable=SC2002
  got_with=$(cat "$work/with-group.sh" | bash -s -- ops 2>&1 || true)
  # shellcheck disable=SC2002
  got_without=$(cat "$work/no-group.sh" | bash -s -- ops 2>&1 || true)

  if printf '%s' "$got_with" | grep -qF MARKER_REACHED; then
    ok 'группа на месте: команда, читающая stdin, не съела тело скрипта'
  else
    bad 'группа на месте' 'метка после читающей stdin команды не напечаталась — значит остаток скрипта потерян, и запуск формой «ssh … bash -s < bootstrap.sh» небезопасен'
  fi
  # Красная ветвь, прогоняемая КАЖДЫЙ раз: без неё первая проверка зеленела
  # бы и на скрипте, которому группа не нужна вовсе, — то есть не отличала бы
  # «защищено» от «нечего защищать».
  if printf '%s' "$got_without" | grep -qF MARKER_REACHED; then
    bad 'мутация краснеет' 'со снятой группой метка всё равно напечаталась — приманка не различает защищённый скрипт от незащищённого'
  else
    ok 'мутация краснеет: со снятой группой тело скрипта теряется'
  fi
fi

printf '\nитог: %d прошло, %d провалилось\n' "$pass" "$fail"
[ "$fail" -eq 0 ]
