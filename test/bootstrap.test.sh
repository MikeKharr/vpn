#!/usr/bin/env bash
# Приманки deploy/bootstrap.sh. Прогоняются на своей машине и в CI, без
# сервера и без root.
#
# Что здесь ВООБЩЕ можно проверить без машины, а что нельзя, названо прямо:
#   можно — разбор аргументов (имя пользователя выкатки, второй аргумент) и
#           то, что запуск СО STDIN не теряет тело скрипта;
#   нельзя — ufw, fail2ban, sshd, Docker и отчёт: они требуют root и Ubuntu.
#           Их различает только живой прогон на сервере, и его вывод —
#           доказательство в описании PR, а не этот файл.
#
# Главная приманка — «stdin не съедается». Разрешение владельца 2026-10-06
# запускать скрипт формой `ssh triplify 'bash -s -- ops' < deploy/bootstrap.sh`
# опирается ровно на одно свойство файла: тело завёрнуто в группу `{ … }`, и
# bash дочитывает её до закрывающей скобки ПРЕЖДЕ, чем исполнить хоть одну
# команду внутри. Без группы первая же команда, читающая stdin (а это apt на
# conffile-вопросе — урок адвента 2026-09-07), съедает ОСТАТОК СКРИПТА:
# прогон при этом выглядит успешным, потому что не исполненные строки не
# жалуются. Приманка ловит именно это и именно через конвейер — через файл
# stdin перемещаемый, и bash возвращает позицию сам, то есть отказ не
# воспроизводится.
set -euo pipefail

here=$(cd "$(dirname "$0")" && pwd)
script="$here/../deploy/bootstrap.sh"
[ -r "$script" ] || { echo "нет $script"; exit 2; }

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

pass=0
fail=0

ok()   { pass=$((pass + 1)); printf 'ok   %s\n' "$1"; }
bad()  { fail=$((fail + 1)); printf 'ПРОВАЛ %s: %s\n' "$1" "$2"; }

# $1 — заголовок, $2 — ожидаемый код, $3 — кусок, который обязан быть в
# выводе, далее — аргументы скрипта. Запуск ФАЙЛОМ: проверяется разбор
# аргументов, а не чтение ввода.
case_is() {
  local title="$1" want_rc="$2" needle="$3"; shift 3
  local out rc=0
  out=$(bash "$script" "$@" 2>&1) || rc=$?
  if [ "$rc" != "$want_rc" ]; then
    bad "$title" "ждали код $want_rc, получили $rc"
    return
  fi
  if ! printf '%s' "$out" | grep -qF -- "$needle"; then
    bad "$title" "в выводе нет куска «$needle»"
    return
  fi
  ok "$title"
}

echo '--- аргументы: имя пользователя выкатки ---'
# Имя не задано — отказ, а не умолчание. Умолчание в файле означало бы, что
# на третьей машине пользователь выкатки получит имя, которое никто не
# выбирал, и оно же будет известно каждому, кто читает репозиторий.
case_is 'имя не задано — отказ'            1 'не задано имя пользователя' ''
# Имена из списка угадываемых. `ops` в этом списке НЕТ намеренно: его выбрал
# владелец 2026-10-06, и именно он уезжает в секрет SSH_USER.
case_is 'имя root отвергнуто'              1 'угадывается с первой попытки' root
case_is 'имя ubuntu отвергнуто'            1 'угадывается с первой попытки' ubuntu
case_is 'имя advent отвергнуто'            1 'угадывается с первой попытки' advent
case_is 'имя deploy отвергнуто'            1 'угадывается с первой попытки' deploy
# Форма имени: заглавные, точка, начало с цифры, два знака — всё это Linux
# либо не примет, либо примет с сюрпризами в правах на /home.
case_is 'имя с заглавными — отказ по форме' 1 'не той формы' Ops
case_is 'имя с точкой — отказ по форме'     1 'не той формы' 'ops.th2'
case_is 'имя с цифры — отказ по форме'      1 'не той формы' '2ops'
case_is 'имя в два знака — отказ по форме'  1 'не той формы' op

echo '--- аргументы: второй аргумент ---'
# Второй аргумент — только --disable-root-login. Опечатка в нём не должна
# тихо сойти за первую фазу: тогда владелец думал бы, что вход для root
# закрыт, а он был бы открыт.
case_is 'опечатка во втором аргументе — отказ' 1 'может быть только --disable-root-login' ops --disable-root
case_is 'лишний аргумент — отказ'              1 'может быть только --disable-root-login' ops --force

echo '--- годное имя доходит до проверки на root ---'
# Положительный контроль: без него все приманки выше зеленели бы и на
# скрипте, который отвергает ЛЮБОЙ аргумент. Прогон идёт не от root, поэтому
# годное имя обязано дойти именно до этой проверки — и дальше не пойти.
case_is 'ops принят, отказ уже на «не root»'   1 'запускать от root' ops
case_is 'ops --disable-root-login принят'      1 'запускать от root' ops --disable-root-login

echo '--- stdin не съедается при запуске конвейером ---'
# Фикстура собирается ИЗ САМОГО bootstrap.sh и адресуется ПОЗИЦИЕЙ: строкой,
# открывающей группу. Сразу после неё вставляются две строки — команда,
# читающая stdin, и метка. Если тело скрипта не защищено группой, `read`
# съедает строку с меткой, и метка не печатается.
open_line=$(grep -n '^{$' "$script" | head -1 | cut -d: -f1)
if [ -z "$open_line" ]; then
  bad 'фикстура собирается' 'в bootstrap.sh нет строки «{», открывающей группу тела — приманка ниже проверяла бы не то'
else
  awk -v n="$open_line" \
    'NR==n { print; print "read -r stolen || true"; print "echo MARKER_REACHED"; next } { print }' \
    "$script" > "$work/with-group.sh"
  # Мутация: группа снята. Обе скобки заменяются на no-op, то есть тело
  # остаётся тем же набором команд, и меняется ровно одно — разбирает ли bash
  # его целиком до первого исполнения.
  sed -e 's|^{$|: группа снята|' -e 's|^} </dev/null$|: группа снята|' \
    "$work/with-group.sh" > "$work/no-group.sh"
  if ! grep -qF ': группа снята' "$work/no-group.sh"; then
    bad 'мутация собирается' 'замена скобок группы не нашла ни одной строки — мутация ничего не изменила'
  fi

  got_with=$(cat "$work/with-group.sh" | bash -s -- ops 2>&1 || true)
  got_without=$(cat "$work/no-group.sh" | bash -s -- ops 2>&1 || true)

  if printf '%s' "$got_with" | grep -qF MARKER_REACHED; then
    ok 'группа на месте: команда, читающая stdin, не съела тело скрипта'
  else
    bad 'группа на месте' 'метка после читающей stdin команды не напечаталась — значит остаток скрипта потерян, и запуск формой «ssh … bash -s < bootstrap.sh» небезопасен'
  fi
  # Красная ветвь, прогоняемая КАЖДЫЙ раз: без неё первая проверка зеленела
  # бы и на скрипте, которому группа не нужна вовсе, — то есть не отличала бы
  # «защищено» от «нечего защищать».
  if printf '%s' "$got_without" | grep -qF MARKER_REACHED; then
    bad 'мутация краснеет' 'со снятой группой метка всё равно напечаталась — приманка не различает защищённый скрипт от незащищённого'
  else
    ok 'мутация краснеет: со снятой группой тело скрипта теряется'
  fi
fi

printf '\nитог: %d прошло, %d провалилось\n' "$pass" "$fail"
[ "$fail" -eq 0 ]
