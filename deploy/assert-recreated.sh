#!/bin/sh
# Проверяет, что контейнер Xray на сервере ПЕРЕСОЗДАН этой выкаткой, а не
# продолжает работать с прежним конфигом.
#
#   assert-recreated.sh <id xray до> <id xray после> <StartedAt render> <StartedAt xray>
#
# Зачем отдельный держатель. Xray читает config.json один раз на старте и
# перезагрузки конфигурации не умеет (у Caddy в соседних проектах есть
# `caddy reload`, здесь аналога нет). Поэтому `render` может собрать новый
# файл в tmpfs, а живой Xray продолжит работать со старым, и тогда:
#   - ротация приватного ключа не вступает в силу — владелец переустановит
#     ссылки по новому pbk, и ОБА устройства перестанут подключаться;
#   - отзыв устройства не вступает в силу — удалённый UUID продолжит
#     подключаться.
# В обоих случаях выкатка зелёная, `render` healthy, у `xray` Running=true и
# RestartCount=0. Именно `RestartCount=0` эти две гипотезы НЕ различает:
# «устойчив» и «устойчив с прежним конфигом» дают одно и то же число.
#
# Что различает: идентификатор контейнера. Пересозданный контейнер — другой
# объект с другим Id, и его процесс читал тот файл, который лежал в томе на
# момент его старта. Цепочка «новый файл» → «новый процесс его прочитал»
# замыкается порядком в compose: `xray` зависит от `render` условием
# service_healthy, а healthcheck `render` — это наличие собранного файла.
#
# Вторая проверка, времена старта, держит именно это звено: если из compose
# уберут depends_on, Xray сможет стартовать раньше, чем файл собран, и
# «другой Id» перестанет значить «прочитал новый файл».
#
# Коды: 0 — пересоздан, 1 — нет, 2 — проверка не выполнилась.
set -eu

if [ "$#" -ne 4 ]; then
  echo "assert-recreated.sh: ожидается 4 аргумента, получено $#" >&2
  exit 2
fi

id_before="$1"
id_after="$2"
render_started="$3"
xray_started="$4"

if [ -z "$id_after" ]; then
  echo "::error::после выкатки контейнера xray нет вовсе — он не поднялся"
  exit 1
fi

if [ -z "$id_before" ]; then
  echo "ok: контейнера xray до выкатки не было (первая выкатка на эту машину)"
else
  if [ "$id_before" = "$id_after" ]; then
    echo "::error::контейнер xray НЕ пересоздан (тот же Id) — Xray читает config.json только на старте, значит ротация ключа и отзыв устройства не вступили в силу, хотя выкатка выглядит удачной"
    exit 1
  fi
  echo "ok: контейнер xray пересоздан (Id сменился)"
fi

# Время старта. Docker отдаёт RFC3339 с переменным числом знаков в дробной
# части, поэтому строки сравнивать напрямую нельзя: «…33.3Z» лексикографически
# больше «…33.25Z». Приводятся к одной ширине, и только тогда лексикографический
# порядок совпадает с числовым. В целочисленную арифметику shell эти 23 знака
# не влезают, поэтому сравнение идёт через sort, а не через -gt.
norm() {
  printf '%s' "$1" | awk '{
    t = $0
    gsub(/[-:TZ]/, "", t)
    n = index(t, ".")
    if (n) { frac = substr(t, n + 1); t = substr(t, 1, n - 1) } else { frac = "" }
    while (length(frac) < 9) { frac = frac "0" }
    print t substr(frac, 1, 9)
  }'
}

r=$(norm "$render_started")
x=$(norm "$xray_started")
case "$r$x" in
  *[!0-9]*|'') echo "::error::время старта не разобралось: render='$render_started' xray='$xray_started'"; exit 2 ;;
esac
if [ "${#r}" -ne "${#x}" ]; then
  echo "::error::времена старта разной ширины после приведения: '$r' и '$x'"
  exit 2
fi

earliest=$(printf '%s\n%s\n' "$r" "$x" | LC_ALL=C sort | head -1)
if [ "$earliest" != "$r" ]; then
  echo "::error::xray стартовал РАНЬШЕ render — значит он читал конфиг, которого ещё не было, или прежний; проверьте depends_on: render condition service_healthy в compose.yml"
  exit 1
fi
echo "ok: xray стартовал не раньше render, то есть читал собранный этой выкаткой конфиг"
