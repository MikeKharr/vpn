#!/bin/sh
# Единица `render`: собирает config.json в общий tmpfs-том и остаётся жить.
#
# Почему не одноразовый контейнер (`restart: "no"` + depends_on
# service_completed_successfully). Том на tmpfs пустеет при перезапуске
# демона Docker и при перезагрузке хоста, а одноразовую службу демон
# обратно не поднимает: Xray после ребута стартовал бы на пустом каталоге и
# крутился бы в отказе, пока кто-нибудь не зайдёт руками. Долгоживущая
# единица с restart: unless-stopped пересобирает конфиг на каждом своём
# старте, то есть после ребута том заполняется сам.
#
# Спать, а не выходить: пока контейнер жив, у тома есть держатель, и
# healthcheck «файл на месте» остаётся осмысленным признаком готовности для
# depends_on у Xray.
#
# sleep без аргумента-бесконечности: busybox `sleep infinity` понимает не во
# всех сборках, а молча не спящий цикл сжёг бы ядро.
set -eu

/render/render.sh

while true; do
  sleep 86400
done
