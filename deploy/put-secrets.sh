#!/usr/bin/env bash
# Кладёт deploy/secrets.env этого проекта на сервер. Запускает ВЛАДЕЛЕЦ со
# своей машины: новый секрет на сервере — только его руками (AGENTS.md).
#
# Форма — по образцу deploy/put-secrets.sh адвента: значения вводятся скрытно
# (`read -rs`), уходят на сервер по stdin через ssh и поэтому не попадают ни в
# историю shell, ни в список процессов, ни в вывод, ни на диск этой машины.
# Файл на сервере создаётся под umask 077 и получает chmod 600.
#
# Значения владелец получает у себя же (ADR 2026-10-03-0353, «Ручные шаги», п. 4):
#   uuidgen             → по одному на устройство (на th2 — ТЕ ЖЕ, что на th1)
#   openssl rand -hex 4 → по одному на устройство (на th2 — ТЕ ЖЕ, что на th1)
# Ничего из этого не вставлять в чат агенту.
#
# ПАРА x25519 ГЕНЕРИРУЕТСЯ ОДИН РАЗ НА СЕРВЕР И БОЛЬШЕ НЕ МЕНЯЕТСЯ (требование
# владельца 2026-10-06: конфиг клиента должен быть окончательным с первого
# импорта). Для th2 она УЖЕ СУЩЕСТВУЕТ, и новой быть не должно:
#
#   приватная половина — ~/.config/vpn/th2-reality.key на Mac владельца;
#   публичная          — ~/.config/vpn/th2-reality.pub, и она УЖЕ уехала в
#                        импортированный профиль Happ на обоих устройствах.
#
# Профиль th2 импортирован ОКОНЧАТЕЛЬНО: переимпорт требует заново принести
# конфиг на устройство, а делать это из России при лежащем VPN — ровно то
# положение, которого вторая машина и должна избегать (ADR 2026-10-06-1054).
# Поэтому на запрос REALITY_PRIVATE_KEY для th2 вставляется содержимое
# ~/.config/vpn/th2-reality.key, а `docker run … x25519` для th2 НЕ
# ЗАПУСКАЕТСЯ: новая пара сделала бы импортированный профиль мёртвым, и
# починка потребовала бы того самого переимпорта.
#
# Ни bootstrap, ни выкатка ключа не генерируют и не касаются его вовсе: Xray
# читает его из отрендеренного конфига, рендер — из этого файла, и больше
# нигде он не возникает. Ротация остаётся возможной
# (`docker run --rm ghcr.io/xtls/xray-core:26.9.30 x25519` → PrivateKey и
# Password), но это осознанный переимпорт на обоих устройствах, а не попутное
# следствие выкатки.
#
# Запуск:  SERVER=<user>@<host> bash deploy/put-secrets.sh
# Переопределения: SSH_KEY=/путь/к/ключу, SSH_PORT=22
#
# SERVER обязателен и умолчания НЕ имеет (ADR 2026-10-05-2223, п. 3).
# Серверов два, ключ REALITY у каждого свой, и умолчание означало бы, что
# запуск без переменной молча уносит ключ th2 на th1: там он лёг бы поверх
# рабочего, Xray пересоздался бы следующей выкаткой с чужим ключом, и оба
# устройства перестали бы подключаться к РЕЗЕРВУ — при живом основном это
# нашлось бы только в день отказа th2.
set -euo pipefail

if [ -z "${SERVER:-}" ]; then
  cat >&2 <<'USAGE'
Не задан SERVER — на какой сервер класть секреты. Умолчания нет намеренно:
ключ REALITY у каждого сервера свой (ADR 2026-10-05-2223, п. 3), и молчаливое
умолчание унесло бы ключ одного хоста на другой.

  SERVER=<пользователь>@45.91.134.23  bash deploy/put-secrets.sh   # th1, резерв
  SERVER=<пользователь>@160.236.128.28 bash deploy/put-secrets.sh  # th2, основной

Имя пользователя выкатки — то, что выбрано при bootstrap (deploy/bootstrap.sh);
в репозитории его нет, оно живёт в секрете SSH_USER своего environment.
USAGE
  exit 1
fi
SSH_PORT="${SSH_PORT:-22}"
REMOTE_PATH="vpn/deploy/secrets.env"

ssh_args=(-p "$SSH_PORT")
if [ -n "${SSH_KEY:-}" ]; then
  ssh_args+=(-i "$SSH_KEY")
fi

# Форма значений проверяется здесь, чтобы опечатка не доехала до сервера и не
# превратилась в контейнер, который падает на старте. Держателем формы остаётся
# deploy/render/render.sh: он проверяет то же самое уже на сервере, и это он
# решает, годен ли файл.
ask() {
  local name="$1" prompt="$2" form="$3" hint="$4" value=''
  while true; do
    printf '%s (ввод не отображается)\n> ' "$prompt"
    read -rs value || true
    printf '\n'
    if [ -z "$value" ]; then
      echo "Пусто — ничего не записано, выхожу." >&2
      exit 1
    fi
    if printf '%s' "$value" | grep -Eq "$form"; then
      break
    fi
    echo "Не та форма: ожидается $hint. Повторите." >&2
  done
  eval "$name=\$value"
}

UUID_RE='^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[1-5][0-9a-fA-F]{3}-[89abAB][0-9a-fA-F]{3}-[0-9a-fA-F]{12}$'

# Приглашение называет ОБА источника значения, потому что их два и они не
# взаимозаменяемы: у th1 ключ берётся из вывода `xray x25519`, у th2 — из
# уже созданного `~/.config/vpn/th2-reality.key` (его публичная половина
# стоит в импортированном профиле Happ, и новая пара отрезала бы клиента от
# th2 — README, «Клиент с автопереключением»). Переносить значение буфером:
# `pbcopy < ~/.config/vpn/th2-reality.key`, вставить здесь, затем
# `pbcopy < /dev/null`.
ask REALITY_PRIVATE_KEY 'PrivateKey: у th1 — из вывода xray x25519, у th2 — из ~/.config/vpn/th2-reality.key (переносить pbcopy, не печатая)' '^[A-Za-z0-9_-]{43}$' '43 знака base64url'
ask UUID_MAC            'UUID устройства Mac'              "$UUID_RE"            'UUID из uuidgen'
ask UUID_IPHONE         'UUID устройства iPhone'           "$UUID_RE"            'UUID из uuidgen'
ask SHORTID_MAC         'shortId устройства Mac'           '^[0-9a-f]{8}$'       '8 знаков hex, openssl rand -hex 4'
ask SHORTID_IPHONE      'shortId устройства iPhone'        '^[0-9a-f]{8}$'       '8 знаков hex, openssl rand -hex 4'

if [ "$UUID_MAC" = "$UUID_IPHONE" ] || [ "$SHORTID_MAC" = "$SHORTID_IPHONE" ]; then
  echo "Значения устройств совпали: отзыв одного отозвал бы оба. Ничего не записано." >&2
  exit 1
fi

# Скрипт исполняется на сервере, значения приходят по одному в строке stdin.
# Файл перезаписывается целиком: в нём ровно пять строк, и «сохранить
# остальное» тут нечего — в отличие от общего secrets.env адвента.
# XRAY_TARGET сюда НЕ попадает: это не секрет, а строка межрепозиторного
# контракта, и она живёт в deploy/compose.yml, где её держит шаг CI. Иначе
# смена одного не-секрета требовала бы заново ввести пять секретов
# (находка reviewer).
REMOTE_SCRIPT=$(cat <<REMOTE
set -eu
umask 077
f="${REMOTE_PATH}"
mkdir -p "\$(dirname "\$f")"
read -r key
read -r uuid_mac
read -r uuid_iphone
read -r sid_mac
read -r sid_iphone
tmp="\$(mktemp "\$(dirname "\$f")/.secrets.XXXXXX")"
trap 'rm -f "\$tmp"' EXIT
{ echo '# Секреты VPN. Только на сервере, chmod 600. Создан deploy/put-secrets.sh.'
  echo '# Читает их ТОЛЬКО контейнер render; у контейнера xray env_file нет.'
  printf 'REALITY_PRIVATE_KEY=%s\n' "\$key"
  printf 'UUID_MAC=%s\n' "\$uuid_mac"
  printf 'UUID_IPHONE=%s\n' "\$uuid_iphone"
  printf 'SHORTID_MAC=%s\n' "\$sid_mac"
  printf 'SHORTID_IPHONE=%s\n' "\$sid_iphone"
} > "\$tmp"
mv "\$tmp" "\$f"
trap - EXIT
chmod 600 "\$f"
ls -l "\$f"
# Печатаются ИМЕНА и длины, не значения: эта сессия не должна увидеть ключ.
awk -F= '/^[A-Z]/ { printf "%s: %d знаков\n", \$1, length(\$2) }' "\$f"
REMOTE
)

# SC2029: подстановка на стороне клиента здесь и нужна — REMOTE_SCRIPT собран
# выше ровно для того, чтобы уехать текстом, как в put-secrets.sh адвента.
# shellcheck disable=SC2029
printf '%s\n%s\n%s\n%s\n%s\n' \
  "$REALITY_PRIVATE_KEY" "$UUID_MAC" "$UUID_IPHONE" \
  "$SHORTID_MAC" "$SHORTID_IPHONE" \
  | ssh "${ssh_args[@]}" "$SERVER" "$REMOTE_SCRIPT"

cat <<'EOF'

Осталось сделать:
  1. Пересоздать контейнеры, иначе новые значения не вступят в силу:
     render соберёт новый конфиг, а живой Xray продолжит работать с прежним —
     он читает config.json один раз на старте и reload'а не умеет.
       push в main или workflow_dispatch «deploy» в GitHub Actions.
     Руками на сервере — только владельцу, и ОБЯЗАТЕЛЬНО с наложением своего
     хоста (без него render отказывается: нет XRAY_TARGET и MASK_NAME):
       cd vpn/deploy && docker compose -f compose.yml -f hosts/<хост>/compose.yml \
         up -d --force-recreate
  2. При ротации ключа, UUID или shortId — обновить КЛИЕНТЫ, иначе ротация
     выглядит сделанной, а туннель молча мёртв. Действующий профиль —
     «TH failover», то есть JSON, и переимпорт ссылок его НЕ обновляет:
       bash bin/make-happ-json.sh — собрать JSON заново и переимпортировать
         его в Happ на ОБОИХ устройствах (через буфер);
       bash bin/make-link.sh <устройство> <хост> — ссылки, если ими
         пользуются как полом. Публичный ключ у хостов РАЗНЫЙ: ссылки того
         хоста, чей ключ только что заменён, собираются заново, ссылки
         другого — нет.
     Полный порядок — README, «Ротация UUID и shortId: четыре шага, не два».
  3. UUID и shortId устройств — ОДНИ И ТЕ ЖЕ на обоих серверах (ADR
     2026-10-05-2223, п. 3): отзыв устройства — это запуск этого скрипта
     дважды, по разу на хост. Ключ REALITY при этом у каждого свой.
EOF
